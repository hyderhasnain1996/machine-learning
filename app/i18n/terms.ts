/** Returns the Korean term when the site is in Korean, otherwise the original text. */
export function translateTerm(text: string, lang: string): string {
  if (lang !== 'ko' || !text) return text
  return koTerms[text] ?? koTerms[text.trim()] ?? text
}

/** Hook form: const k = useTerm(); k('Deep Learning') */
export function useTerm() {
  const { lang } = useLanguage()
  return (text: string) => translateTerm(text, lang)
}
